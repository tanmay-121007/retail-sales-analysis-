-- Q)	Which product category generates the highest revenue

select Product_Category, sum(Total_Amount) as revenue from retail_sales_dataset 
group by Product_Category
order by revenue desc ;

-- Q)	Which gender contributes the most revenue?
select Gender, sum(Total_Amount) as revenue from retail_sales_dataset 
group by Gender
order by revenue desc ;

-- Q)	Find the total quantity of products sold ?
select Product_Category,sum(Quantity) as quantity from retail_sales_dataset
group by Product_Category
order by quantity desc ;

-- Q)	Find the average age of customers ?
select AVG(Age) as AVG_Age from retail_sales_dataset ;

-- Q)	Find the total revenue generated by each product category ?
select Product_Category, sum(Total_Amount) as revenue_generated from retail_sales_dataset
group by Product_Category
order by revenue_generated desc ;

-- Q)	Find the number of transactions made by male and female customers ?
select Gender, count(Transaction_ID) as transaction_made from retail_sales_dataset
group by Gender
order by transaction_made desc ;

-- Q)	Find the top 10 highest-value transactions ?
select Customer_ID, Product_Category, Quantity, Total_Amount from retail_sales_dataset
order by Total_Amount desc
limit 10 ;